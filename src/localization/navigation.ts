export const translateNavigationLabel = (label: unknown) => {
  if (typeof label !== 'string') return ''
  const normalized = label.replace(/\s+/g, ' ').trim()
  const key = navigationLabelKeys[label] ?? navigationLabelKeys[normalized] ?? normalized
  return i18n.global.te(key) ? translate(key) : translateMessage(normalized)
}
